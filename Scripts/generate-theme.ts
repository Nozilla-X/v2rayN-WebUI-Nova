/*
 * Regenerate the Material 3 color-role layer from the Nova brand seed.
 *
 * material-color-utilities ships unbundled ESM; esbuild (already part of the
 * Vite toolchain) resolves it, then the generated role map is written as plain
 * CSS custom properties. `npm run theme` keeps the palette reproducible.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SEED = '#4C5BD4'

const bundled = await build({
  stdin: {
    contents: "export * from '@material/material-color-utilities'",
    resolveDir: root,
    loader: 'js',
  },
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'node',
  logLevel: 'silent',
})
const moduleUrl = `data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0]?.text ?? '').toString('base64')}`
const mcu = await import(moduleUrl)

interface ColorRoles {
  color: number
  onColor: number
  colorContainer: number
  onColorContainer: number
}

interface CustomColor {
  color: { name: string }
  light: ColorRoles
  dark: ColorRoles
}

interface SchemeLike {
  toJSON(): Record<string, number>
}

interface TonePalette {
  tone(tone: number): number
}

type ColorMode = 'light' | 'dark'

const theme = mcu.themeFromSourceColor(mcu.argbFromHex(SEED), [
  { name: 'success', value: mcu.argbFromHex('#2E7D32'), blend: true },
  { name: 'warning', value: mcu.argbFromHex('#8A6100'), blend: true },
])
const camelToKebab = (value: string): string => value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)
const hex = (value: number): string => mcu.hexFromArgb(value)

function roleLines(scheme: SchemeLike, customColors: Record<string, ColorRoles>, neutral: TonePalette, mode: ColorMode): string {
  const lines: string[] = []
  for (const [role, value] of Object.entries(scheme.toJSON())) {
    lines.push(`  --md-sys-color-${camelToKebab(role)}: ${hex(value)};`)
  }
  const tones = mode === 'light'
    ? { surfaceDim: 87, surfaceBright: 98, surfaceContainerLowest: 100, surfaceContainerLow: 96, surfaceContainer: 94, surfaceContainerHigh: 92, surfaceContainerHighest: 90 }
    : { surfaceDim: 6, surfaceBright: 24, surfaceContainerLowest: 4, surfaceContainerLow: 10, surfaceContainer: 12, surfaceContainerHigh: 17, surfaceContainerHighest: 22 }
  for (const [role, tone] of Object.entries(tones)) {
    lines.push(`  --md-sys-color-${camelToKebab(role)}: ${hex(neutral.tone(tone))};`)
  }
  lines.push(`  --md-sys-color-surface-tint: var(--md-sys-color-primary);`)
  for (const [suffix, roles] of Object.entries(customColors)) {
    lines.push(`  --nova-color-${suffix}: ${hex(roles.color)};`)
    lines.push(`  --nova-color-on-${suffix}: ${hex(roles.onColor)};`)
    lines.push(`  --nova-color-${suffix}-container: ${hex(roles.colorContainer)};`)
    lines.push(`  --nova-color-on-${suffix}-container: ${hex(roles.onColorContainer)};`)
  }
  return lines.join('\n')
}

function customFor(mode: ColorMode): Record<string, ColorRoles> {
  return Object.fromEntries((theme.customColors as CustomColor[]).map((custom) => [custom.color.name, custom[mode]]))
}

const lightCustom = customFor('light')
const darkCustom = customFor('dark')

const light = roleLines(theme.schemes.light, lightCustom, theme.palettes.neutral, 'light')
const dark = roleLines(theme.schemes.dark, darkCustom, theme.palettes.neutral, 'dark')

const output = `/* Generated by Scripts/generate-theme.ts from ${SEED}. Do not edit by hand. */
:root {
  color-scheme: light;

${light}

  /* M3 deprecated background roles as aliases of surface. */
  --md-sys-color-background: var(--md-sys-color-surface);
  --md-sys-color-on-background: var(--md-sys-color-on-surface);
}

:root[data-theme="dark"] {
  color-scheme: dark;

${dark}

  --md-sys-color-background: var(--md-sys-color-surface);
  --md-sys-color-on-background: var(--md-sys-color-on-surface);
}
`

const target = path.join(root, 'Src/Design/color-roles.css')
fs.writeFileSync(target, output)
console.log(`Wrote ${path.relative(root, target)} from seed ${SEED}`)

function readPaths(file: string): string[] {
  const source = fs.readFileSync(file, 'utf8')
  return [...source.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((match) => match[1] ?? '')
}

const entries: Array<[name: string, outlined: string[], filled: string[]]> = []
const missing: string[] = []
for (const [name, glyph] of Object.entries(ICONS)) {
  const outlinedFile = path.join(iconRoot, `${glyph}.svg`)
  const filledFile = path.join(iconRoot, `${glyph}-fill.svg`)
  if (!fs.existsSync(outlinedFile)) {
    missing.push(`${name} → ${glyph}`)
    continue
  }
  const outlined = readPaths(outlinedFile)
  const filled = fs.existsSync(filledFile) ? readPaths(filledFile) : outlined
  if (!outlined.length) {
    missing.push(`${name} → ${glyph} (no path data)`)
    continue
  }
  entries.push([name, outlined, filled])
}
if (missing.length) {
  console.error(`Missing Material Symbols:\n  ${missing.join('\n  ')}`)
  process.exitCode = 1
}

const quote = (value: string): string => `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`
const body = entries.map(([name, outlined, filled]) => {
  const o = outlined.map(quote).join(', ')
  const f = filled.map(quote).join(', ')
  return `  ${quote(name)}: { outlined: [${o}], filled: [${f}] },`
}).join('\n')

const output = `/* Generated by Scripts/generate-icons.ts — do not edit by hand. */
export interface IconGlyph {
  outlined: string[]
  filled: string[]
}

export const MATERIAL_ICONS: Record<string, IconGlyph> = {
${body}
}
`

const target = path.join(root, 'Src/Components/Material/icons/generated.ts')
fs.writeFileSync(target, output)
console.log(`Generated ${entries.length} Material Symbols into ${path.relative(root, target)}`)
